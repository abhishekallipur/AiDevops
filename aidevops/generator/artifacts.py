def _compose(project_name: str, port: int) -> str:
    return f"""# Generated by Autonomous AI DevOps Engineer.
# No Docker socket, no privileged mode, no host credential mounts.
services:
  app:
    build: .
    image: {project_name}:local
    ports:
      - "{port}:{port}"
    restart: unless-stopped
"""


def _python_ci() -> str:
    return """name: CI
on:
  push:
  pull_request:

jobs:
  test:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-python@v5
        with:
          python-version: "3.12"
      - run: pip install -r requirements.txt || pip install .
      - run: pip install pytest
      - run: python -m pytest
"""


def _node_ci() -> str:
    return """name: CI
on:
  push:
  pull_request:

jobs:
  test:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: "20"
      - run: npm ci || npm install
      - run: npm test
"""


def _ci_workflow(profile: ProjectProfile) -> str | None:
    if profile.project_type == ProjectType.PYTHON:
        return _python_ci()
    if profile.project_type == ProjectType.NODE:
        return _node_ci()
    return None


def _project_name(profile: ProjectProfile) -> str:
    name = Path(profile.root).name or "app"
    return re.sub(r"[^a-zA-Z0-9._-]", "-", name).lower() or "app"


def build_artifact_contents(
    profile: ProjectProfile, plan: DeploymentPlan
) -> list[tuple[str, str, str, list[str]]]:
    """Return (path, kind, content, notes) tuples for the artifacts to generate.

    The plan's ``artifacts`` list is treated as a floor, not a ceiling: because
    an LLM plan may omit a relevant artifact, a detected port additionally
    warrants Compose and detected tests without existing CI additionally warrant
    a workflow. This keeps the mock and LLM paths consistent.
    """

    if profile.suggested_port:
        plan = plan.model_copy(update={"exposed_port": profile.suggested_port})
    requested = {spec.kind for spec in plan.artifacts}
    if plan.exposed_port:
        requested.add("docker-compose.yml")
    if profile.test_locations and not profile.existing_ci_files:
        requested.add("ci_workflow")

    notes_extra: list[str] = []
    base, image_fallback = _safe_image(
        plan.base_image, DEFAULT_BASE_IMAGE.get(profile.project_type, "alpine:3.20")
    )
    if image_fallback:
        notes_extra.append("Plan base_image was invalid; used a known-good default.")

    builder = _BUILDERS.get(profile.project_type, _unknown_dockerfile)
    existing = Path(profile.root) / "Dockerfile"
    if "Dockerfile" in profile.existing_dockerfiles and existing.is_file() and not existing.is_symlink() and existing.stat().st_size <= 200_000:
        dockerfile = existing.read_text(encoding="utf-8", errors="replace")
        df_notes = ["Using the project's existing Dockerfile. Review its build commands before approval."]
    else:
        dockerfile, df_notes = builder(profile, plan, base)
    df_notes = notes_extra + df_notes

    results: list[tuple[str, str, str, list[str]]] = [
        ("Dockerfile", "Dockerfile", dockerfile, df_notes),
        (".dockerignore", ".dockerignore", _dockerignore(), []),
    ]

    if "docker-compose.yml" in requested and plan.exposed_port:
        results.append(
            (
                "docker-compose.yml",
                "docker-compose.yml",
                _compose(_project_name(profile), plan.exposed_port),
                [],
            )
        )

    if "ci_workflow" in requested and not profile.existing_ci_files:
        ci = _ci_workflow(profile)
        if ci:
            results.append((".github/workflows/ci.yml", "ci_workflow", ci, []))
        else:
            notes_extra.append("CI workflow skipped: no template for this project type.")

    return results


def generate_artifacts(
    profile: ProjectProfile, plan: DeploymentPlan, workspace: Path, settings: Settings
) -> tuple[list[GeneratedArtifact], list[ValidationReport]]:
    """Generate, write, and validate artifacts in ``workspace``."""

    contents = build_artifact_contents(profile, plan)
    has_dockerignore = any(kind == ".dockerignore" for _, kind, _, _ in contents)

    artifacts: list[GeneratedArtifact] = []
    reports: list[ValidationReport] = []

    for rel_path, kind, content, notes in contents:
        write_artifact(workspace, rel_path, content)
        artifact = GeneratedArtifact(path=rel_path, kind=kind, content=content, notes=list(notes))
        report = validate_artifact(artifact, has_dockerignore=has_dockerignore)
        artifact.verified = report.passed and not notes
        artifacts.append(artifact)
        reports.append(report)

    log.info("artifacts generated", extra={"event": "generate", "tool": "generator"})
    return artifacts, reports
