"""Project-specific DevOps artifact generation.

Artifacts are derived from the :class:`ProjectProfile` (evidence) and the
:class:`DeploymentPlan`. Values taken from the plan are sanitized before being
interpolated into a Dockerfile so a hostile or malformed plan cannot inject
arbitrary instructions. Nothing here writes to the source repository — output
goes to an isolated workspace via :mod:`aidevops.generator.workspace`.
"""

